// Turn a Bank_Pro_AI v1 (PPO) policy export (weights.json from export_weights.py) into js/net-weights.mjs.
// Usage: node tools/export-net.mjs <weights.json> [label]
import fs from "node:fs";
const [src, label = ""] = process.argv.slice(2);
const j = JSON.parse(fs.readFileSync(src, "utf8"));
const W = j.weights;
const r = (x) => +x.toFixed(4);
const flat = (m) => m.map((row) => row.map(r));
const out = {
  from: label || "Bank_Pro_AI v1 PPO, batch " + j.batch_num, inputs: j.state_size, hidden: j.hidden_size,
  w0: flat(W["net.0.weight"]), b0: W["net.0.bias"].map(r),
  w1: flat(W["net.2.weight"]), b1: W["net.2.bias"].map(r),
  w2: flat(W["net.4.weight"]), b2: W["net.4.bias"].map(r),
};
fs.writeFileSync(new URL("../js/net-weights.mjs", import.meta.url),
  "// Generated by tools/export-net.mjs from the trained Bank_Pro_AI policy. Do not edit.\nexport const NET = " + JSON.stringify(out) + ";\n");
console.log("wrote js/net-weights.mjs", out.from);
